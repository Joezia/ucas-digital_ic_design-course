			IDLE:begin
				if(sop_in && valid_in)begin
					cnt					<=	{9{np == 2'b00}} & 9'd63	|
											{9{np == 2'b01}} & 9'd127	|
											{9{np == 2'b10}} & 9'd255	|
											{9{np == 2'b11}} & 9'd511	;
					idx					<= idx + 9'd1;
					x_re_sort[idx_sort]	<= x_re;
					x_im_sort[idx_sort]	<= inv ? (~x_im + 1) : x_im;
				end
				else if(cnt == 0)begin
					state				<= CAL;
					stage				<= 4'd1;
					idx					<= 0;
					cnt					<=	{9{np == 2'b00}} & 9'd6	|
											{9{np == 2'b01}} & 9'd7	|
											{9{np == 2'b10}} & 9'd8	|
											{9{np == 2'b11}} & 9'd9	;
					x_re_sort_reg		<= x_re_512_pack;
					x_im_sort_reg		<= x_im_512_pack;
				end
				else if(valid_in)begin
					cnt					<= cnt - 9'd1;
					idx					<= idx + 9'd1;
					x_re_sort[idx_sort]	<= x_re;
					x_im_sort[idx_sort]	<= inv ? (~x_im + 1) : x_im;
				end
			end
			CAL:begin
				if(cnt == 9'd1)begin
					state				<= FINISH;
					
					valid_out			<= 1'b1;
					sop_out				<= 1'b1;
					cnt					<=	{9{np == 2'b00}} & 9'd63	|
											{9{np == 2'b01}} & 9'd127	|
											{9{np == 2'b10}} & 9'd255	|
											{9{np == 2'b11}} & 9'd511	;
					idx					<= 0;
				end
				else begin
					cnt					<= cnt - 9'd1;
					stage				<= stage + 4'd1;
					
					x_re_sort_reg		<= x_re_512_o;
					x_im_sort_reg		<= x_im_512_o;
				end
			end
			FINISH:begin
					sop_out				<= 0;
				if(cnt == 0)begin
					state				<= IDLE;
					valid_out			<= 0;
					cnt					<= ~0;
					idx					<= 0;	
				end
				else begin
					cnt					<= cnt - 1;
					idx					<= idx + 1;
				end
			end
			default: ;
		endcase
	end
end

